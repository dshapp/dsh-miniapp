import { readStorage, writeStorage } from './store';

/**
 * 配对资料：一台 Mac 一条。
 *
 * 小程序没有 Android Keystore，所以只落普通 wx 存储；字段照 Android 的原样保留——
 * bridgeKey 与 devicePrivateKey 就是 Noise_IK 握手所需的全部输入（见 transport/tunnel/）。
 * pairingToken 用过即清（markConnected）。
 */
export interface ServerProfile {
  id: string;
  name: string;
  proxyHost: string;
  proxyPort: number;
  /** 桥接 X25519 静态公钥，base64url。 */
  bridgeKey: string;
  /** 本机设备 X25519 静态私钥，base64url；公钥就是 deviceId。 */
  devicePrivateKey: string;
  /** 一次性配对码，只在首次连接的握手里用一次，用完清空。 */
  pairingToken?: string;
  addedAt: number;
  lastConnectedAt?: number;
}

export interface ScannedPairing {
  host: string;
  port: number;
  bridgeKey: string;
  token?: string;
  /** Mac 自报的设备名；老版本桥接不带这一项。 */
  deviceName?: string;
}

const PROFILES_KEY = 'dsh.profiles';

// —— base64url 小工具 ——
// 微信小程序有 wx.arrayBufferToBase64，但那是标准 base64（带 +/ 与 =），
// 与配对串里的 base64url 不同，所以这里自己编解码一遍。

const B64_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';

function bytesToBase64Url(bytes: Uint8Array): string {
  let out = '';
  for (let i = 0; i < bytes.length; i += 3) {
    const b0 = bytes[i];
    const b1 = i + 1 < bytes.length ? bytes[i + 1] : 0;
    const b2 = i + 2 < bytes.length ? bytes[i + 2] : 0;
    out += B64_ALPHABET[b0 >> 2];
    out += B64_ALPHABET[((b0 & 0x03) << 4) | (b1 >> 4)];
    if (i + 1 < bytes.length) out += B64_ALPHABET[((b1 & 0x0f) << 2) | (b2 >> 6)];
    if (i + 2 < bytes.length) out += B64_ALPHABET[b2 & 0x3f];
  }
  return out;
}

function base64UrlToBytes(text: string): Uint8Array | undefined {
  const clean = text.replace(/[^A-Za-z0-9_-]/g, '');
  const out = new Uint8Array(Math.floor((clean.length * 6) / 8));
  let bits = 0;
  let value = 0;
  let index = 0;
  for (const char of clean) {
    const digit = B64_ALPHABET.indexOf(char);
    if (digit < 0) return undefined;
    value = (value << 6) | digit;
    bits += 6;
    if (bits >= 8) {
      bits -= 8;
      out[index] = (value >> bits) & 0xff;
      index += 1;
    }
  }
  return out;
}

export function encodeKey(bytes: Uint8Array): string {
  return bytesToBase64Url(bytes);
}

export function decodeKey(text: string): Uint8Array | undefined {
  return base64UrlToBytes(text);
}

const KEY_LENGTH = 32;

/** 二维码里的一行字：dshm://<proxy 主机>:<端口>/<桥接公钥>?name=<Mac 名>#<一次性配对码>。 */
export const PairingPayload = {
  parse(text: string): ScannedPairing | undefined {
    const trimmed = text.trim();
    if (!trimmed.startsWith('dshm://')) return undefined;
    const rest = trimmed.slice('dshm://'.length);
    const hashIndex = rest.indexOf('#');
    const beforeHash = hashIndex >= 0 ? rest.slice(0, hashIndex) : rest;
    const token = hashIndex >= 0 ? rest.slice(hashIndex + 1).trim() : '';
    const queryIndex = beforeHash.indexOf('?');
    const pathPart = queryIndex >= 0 ? beforeHash.slice(0, queryIndex) : beforeHash;
    const query = queryIndex >= 0 ? beforeHash.slice(queryIndex + 1) : '';
    const slash = pathPart.indexOf('/');
    if (slash < 0) return undefined;
    const authority = pathPart.slice(0, slash);
    const bridgeKey = decodeURIComponent(pathPart.slice(slash + 1)).trim();
    if (bridgeKey.length === 0) return undefined;
    const keyBytes = decodeKey(bridgeKey);
    if (keyBytes === undefined || keyBytes.length !== KEY_LENGTH) return undefined;
    const colon = authority.lastIndexOf(':');
    const host = (colon >= 0 ? authority.slice(0, colon) : authority).trim();
    if (host.length === 0) return undefined;
    const rawPort = colon >= 0 ? Number.parseInt(authority.slice(colon + 1), 10) : Number.NaN;
    const port = Number.isFinite(rawPort) && rawPort > 0 ? rawPort : 443;
    let deviceName: string | undefined;
    for (const pair of query.split('&')) {
      const eq = pair.indexOf('=');
      if (eq < 0) continue;
      if (pair.slice(0, eq) === 'name') {
        const value = decodeURIComponent(pair.slice(eq + 1)).trim();
        if (value.length > 0) deviceName = value;
      }
    }
    return { host, port, bridgeKey, token: token.length > 0 ? token : undefined, deviceName };
  },

  /**
   * 扫码页显示的默认名字：用 Mac 自己的设备名。
   *
   * 中转 proxy 是多人多设备共用的，拿它的地址当名字既认不出是哪台 Mac，也会让
   * 同一个中转下的多台 Mac 重名；只有老版本桥接不带设备名时才退回地址。
   */
  suggestedName(text: string): string {
    const scanned = PairingPayload.parse(text);
    return scanned === undefined ? 'Mac' : scanned.deviceName ?? scanned.host;
  },
};

function newId(): string {
  return Date.now().toString(36) + '-' + Math.random().toString(36).slice(2, 10);
}

/**
 * 兜底设备私钥：调用方没给密钥时用。
 *
 * 正常路径是配对页先用 transport/tunnel/device.ts 的 generateDeviceKey 生成好再传进来；
 * 同步的 wx.getRandomValues 一定拿不到随机数，所以这里直接抛错，宁可配对失败也不退化成弱随机。
 */
function requireDevicePrivateKey(): string {
  throw new Error('device key must be generated by transport/tunnel/device.ts');
}

interface PersistedState { profiles: ServerProfile[]; currentId?: string }

function readState(): PersistedState {
  const raw = readStorage(PROFILES_KEY);
  if (raw === undefined) return { profiles: [] };
  try {
    const parsed = JSON.parse(raw) as PersistedState;
    if (!Array.isArray(parsed.profiles)) return { profiles: [] };
    return parsed;
  } catch {
    return { profiles: [] };
  }
}

class ProfileStore {
  private state: PersistedState = readState();
  private readonly listeners = new Set<() => void>();

  /** 缺少 id 时补一个，保证老数据也能用。 */
  constructor() {
    this.state.profiles = this.state.profiles
      .filter(profile => typeof profile?.bridgeKey === 'string')
      .map(profile => ({ ...profile, id: profile.id ?? newId() }));
    const saved = this.state.currentId;
    this.state.currentId = this.state.profiles.some(profile => profile.id === saved)
      ? saved
      : this.state.profiles[0]?.id;
  }

  subscribe = (listener: () => void): (() => void) => {
    this.listeners.add(listener);
    return () => {
      this.listeners.delete(listener);
    };
  };

  get = (): PersistedState => this.state;

  private commit(next: PersistedState): void {
    this.state = next;
    writeStorage(PROFILES_KEY, JSON.stringify(next));
    for (const listener of Array.from(this.listeners)) listener();
  }

  get profiles(): ServerProfile[] {
    return this.state.profiles;
  }

  get currentId(): string | undefined {
    return this.state.currentId;
  }

  get current(): ServerProfile | undefined {
    return this.state.profiles.find(profile => profile.id === this.state.currentId);
  }

  /**
   * 扫码结果入库。同一个桥接公钥就是同一台 Mac：重扫只是换一张新的配对码，
   * 设备密钥保持不变，Mac 那边的设备列表因此不会多出一台。
   */
  add(name: string, payload: string, devicePrivateKey?: string): ServerProfile | undefined {
    const scanned = PairingPayload.parse(payload);
    if (scanned === undefined) return undefined;
    const index = this.state.profiles.findIndex(profile => profile.bridgeKey === scanned.bridgeKey);
    let profile: ServerProfile;
    const profiles = this.state.profiles.slice();
    if (index >= 0) {
      profile = {
        ...profiles[index],
        name,
        proxyHost: scanned.host,
        proxyPort: scanned.port,
        pairingToken: scanned.token,
      };
      profiles[index] = profile;
    } else {
      profile = {
        id: newId(),
        name,
        proxyHost: scanned.host,
        proxyPort: scanned.port,
        bridgeKey: scanned.bridgeKey,
        devicePrivateKey: devicePrivateKey ?? requireDevicePrivateKey(),
        pairingToken: scanned.token,
        addedAt: Date.now(),
      };
      profiles.push(profile);
    }
    this.commit({ profiles, currentId: profile.id });
    return profile;
  }

  rename(id: string, name: string): void {
    const trimmed = name.trim();
    if (trimmed.length === 0) return;
    const index = this.state.profiles.findIndex(profile => profile.id === id);
    if (index < 0) return;
    const profiles = this.state.profiles.slice();
    profiles[index] = { ...profiles[index], name: trimmed };
    this.commit({ ...this.state, profiles });
  }

  remove(id: string): void {
    const profiles = this.state.profiles.filter(profile => profile.id !== id);
    const currentId = this.state.currentId === id ? profiles[0]?.id : this.state.currentId;
    this.commit({ profiles, currentId });
  }

  markConnected(id: string): void {
    const index = this.state.profiles.findIndex(profile => profile.id === id);
    if (index < 0) return;
    const profiles = this.state.profiles.slice();
    profiles[index] = { ...profiles[index], lastConnectedAt: Date.now(), pairingToken: undefined };
    this.commit({ ...this.state, profiles });
  }

  setCurrent(id?: string): void {
    this.commit({ ...this.state, currentId: id });
  }
}

export const profileStore = new ProfileStore();
