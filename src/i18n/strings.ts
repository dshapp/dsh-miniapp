/**
 * t() 风格的格式化：把 %d/%s 占位符填上。
 *
 * 认的形状与安卓 `String.format(Locale.ROOT, …)` 在本端文案里用到的子集一致：
 * `%d`/`%s`、带宽度的 `%02d`（durationMinutes 的秒位补零）、以及转义的 `%%`。
 * 只认 %d/%s 的话，`%dm %02ds` 会把 `%02d` 原样留在界面上（一分钟以上的用时读作
 * "2m %02ds"），`%d%%` 也会多出一个百分号。
 */
export function fmt(template: string, ...args: (string | number)[]): string {
  let i = 0;
  return template.replace(/%%|%(0)?(\d+)?([ds])/g, (whole, zero: string | undefined, width: string | undefined) => {
    if (whole === '%%') return '%';
    let out = String(args[i++] ?? '');
    const pad = width ? Number(width) : 0;
    if (pad > out.length) out = (zero ? '0' : ' ').repeat(pad - out.length) + out;
    return out;
  });
}
